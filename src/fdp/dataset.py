class Dataset(Resource):
    """Class representing a DCATv3 Dataset.

    :var uuid: the uuid that is assigned by the Fair Data Point
    :vartype uuid: str

    The following properties are specific to this class:

    distribution, frequency, in series, spatial/geographic coverage, spatial
    resolution, temporal coverage, temporal resolution, was generated by

    The following properties of the super-class dcat:Resource are also
    available for use:

    access rights, conforms to, contact point, creator, description, has
    policy, identifier, is referenced by, keyword/tag, landing page, license,
    language, relation, rights, qualified relation, publisher, release date,
    theme/category, title, type/genre, update/modification date, qualified
    attribution, has current version, has version, previous version, replaces,
    status, version, version notes, first, last, previous
    """

    URL_PATH = "dataset"

